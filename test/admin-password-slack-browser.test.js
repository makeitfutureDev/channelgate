import test from 'node:test';
import assert from 'node:assert/strict';
import { ensureTestEnv } from './helpers.js';
ensureTestEnv();
delete process.env.ADMIN_PASSWORD;
const { saveSettings } = await import('../src/config/settings.js');
const { hashPassword } = await import('../src/web/security.js');
const { setUser } = await import('../src/config/store.js');
const { createWebApp } = await import('../src/web/app.js');

test('browser completes initial setup and Slack code sign-in without an authenticator', { skip: !process.env.CG_BROWSER_MODULE, timeout: 60_000 }, async (t) => {
  const password = 'disposable-browser-slack-password';
  saveSettings({ publicUrl: '', adminPassword: await hashPassword(password), adminPasswordSlackEnabled: false });
  await setUser('U123456789', { name: 'Fixture administrator', isAdmin: true });
  let code;
  const app = createWebApp({ adminIdentityDelivery: async (_id, text) => { code = text.match(/\b\d{8}\b/)[0]; } });
  const server = await new Promise(resolve => { const s = app.listen(0, '127.0.0.1', () => resolve(s)); });
  t.after(() => new Promise(resolve => { server.closeAllConnections(); server.close(resolve); }));
  const base = `http://localhost:${server.address().port}`;
  const { chromium } = await import(process.env.CG_BROWSER_MODULE);
  const browser = await chromium.launch({ headless: true, executablePath: process.env.CG_BROWSER_EXECUTABLE });
  t.after(() => browser.close());
  const context = await browser.newContext();
  const page = await context.newPage();
  const errors = [];
  page.on('pageerror', error => errors.push(error.message));
  const request = (route, body) => page.evaluate(async ({ route, body }) => {
    const r = await fetch(route, { method: body ? 'POST' : 'GET', headers: { 'Content-Type': 'application/json', 'X-CG-Request': '1' }, ...(body ? { body: JSON.stringify(body) } : {}) });
    return { status: r.status, body: await r.json() };
  }, { route, body });
  await page.goto(`${base}/login.html`);
  await page.locator('#bootstrap').waitFor({ state: 'visible' });
  await page.locator('#bootstrap summary').click();
  await page.locator('#pw').fill(password);
  await page.locator('#bootstrap-submit').click();
  await page.locator('#link-panel').waitFor({ state: 'visible' });
  await page.locator('#link-send').click();
  await page.locator('#link-code').waitFor({ state: 'visible' });
  await page.locator('#link-code').fill(code);
  await page.locator('#link-verify').click();
  await page.locator('#setup-access').waitFor({ state: 'visible' });
  await page.locator('#setup-access').click();
  await page.locator('[data-access="password-slack-save"]').waitFor({ state: 'visible' });
  await page.locator('[data-access="password-slack-password"]').fill(password);
  await page.locator('[data-access="password-slack-enabled"]').check();
  await page.waitForFunction(() => globalThis.document.querySelector('[data-access="password-slack-enabled"]')?.checked && !globalThis.document.querySelector('[data-access="bootstrap"]')?.checkVisibility());
  const me = await request('/api/auth/me');
  assert.equal(me.body.bootstrap, false);
  assert.equal(me.body.passkeys.length, 0);
  assert.equal(me.body.account.userId, 'U123456789');
  assert.equal((await request('/api/settings')).status, 200);
  await request('/api/logout', {});
  await page.goto(`${base}/login.html`);
  await page.locator('#password-slack').waitFor({ state: 'visible' });
  await page.locator('#password-slack summary').click();
  await page.locator('#slack-user').fill('U123456789');
  await page.locator('#slack-password').fill(password);
  await page.locator('#password-slack-form button').click();
  await page.locator('#slack-code').waitFor({ state: 'visible' });
  assert.equal(await page.locator('#slack-password').inputValue(), '');
  await page.locator('#slack-code').fill(code);
  await Promise.all([page.waitForURL(`${base}/`), page.locator('#password-slack-verify-form button').click()]);
  assert.equal((await request('/api/auth/me')).body.account.userId, 'U123456789');
  await page.goto(`${base}/settings#set-admin-access`);
  await page.locator('[data-access="reauth"]').click();
  await page.locator('[data-auth="password"]').fill(password);
  await page.locator('[data-auth="submit"]').click();
  await page.locator('[data-auth="code"]').waitFor({ state: 'visible' });
  await page.locator('[data-auth="code"]').fill(code);
  await page.locator('[data-auth="submit"]').click();
  await page.locator('[data-access="message"]').filter({ hasText: 'Identity verified' }).waitFor();
  await Promise.all([page.waitForURL(`${base}/login.html`), page.locator('[data-access="password-slack-enabled"]').uncheck()]);
  assert.equal((await request('/api/auth/me')).status, 401);
  assert.equal((await request('/api/auth/status')).body.passwordSlackEnabled, false);
  assert.deepEqual(errors, []);
});
