// Exercise the actual admin views and save endpoints against a disposable gateway.
import test from "node:test";
import assert from "node:assert/strict";
import path from "node:path";
import { fileURLToPath } from "node:url";
import express from "express";
import { ensureTestEnv, tempDir, testLicenseEnv } from "./helpers.js";
import { openSetting } from "./settings-navigation-helper.js";
import { ADMIN_VIEW_PATHS } from "../public/admin-routes.js";

ensureTestEnv();
process.env.GATEWAY_SKILL_SOURCES = tempDir("cg-org-destinations-");

test("organization grants and variables have independent routes, drafts and saves", { skip: !process.env.CG_BROWSER_MODULE }, async (t) => {
  const { chromium } = await import(process.env.CG_BROWSER_MODULE);
  const { createAdminRouter } = await import("../src/web/routes/admin.js");
  const { getOrgAccessGrants, saveSettings } = await import("../src/config/settings.js");
  const { setUser } = await import("../src/config/store.js");
  await setUser("U_TEST", { name: "Grants user", approved: true });
  const app = express();
  app.use(express.json());
  app.get("/api/auth/me", (_req, res) => res.json({ bootstrap: false, linkRequired: false, fresh: true, account: { userId: "U_TEST" }, passkeys: [] }));
  app.get("/api/health", (_req, res) => res.json({ slack: { connected: false, status: "off" }, engines: {} }));
  app.get("/api/skills", (_req, res) => res.json({ skills: ["alpha", "beta"] }));
  app.get("/api/mcp/available", (_req, res) => res.json({ servers: [] }));
  app.use("/api", createAdminRouter({ slack: { snapshot: () => ({ status: "disconnected", connected: false }) } }));
  const dir = fileURLToPath(new URL("../public", import.meta.url));
  app.use(express.static(dir, { dotfiles: "allow" }));
  app.get(ADMIN_VIEW_PATHS, (_req, res) => res.sendFile(path.join(dir, "index.html"), { dotfiles: "allow" }));
  const server = await new Promise((resolve) => { const s = app.listen(0, "127.0.0.1", () => resolve(s)); });
  t.after(() => new Promise((resolve) => { server.closeAllConnections(); server.close(resolve); }));
  const browser = await chromium.launch({ headless: true, executablePath: process.env.CG_BROWSER_EXECUTABLE, args: ["--no-sandbox"] });
  t.after(() => browser.close());
  const page = await browser.newPage({ viewport: { width: 1440, height: 900 } });
  page.setDefaultTimeout(10000);
  const errors = [];
  page.on("pageerror", (error) => errors.push(error.message));
  const base = `http://127.0.0.1:${server.address().port}`;
  const nav = (name) => page.locator(`.nav-item[data-view="${name}"]`).click();
  const created = await fetch(base + "/api/skills/catalog", {
    method: "POST", headers: { "Content-Type": "application/json" },
    body: JSON.stringify({ publish: false, files: [{ path: "SKILL.md", content: "---\nname: alpha\ndescription: Grant test skill\n---\n\n# Alpha\n" }] }),
  });
  assert.equal(created.status, 201);
  const alpha = page.locator('#org-grants-editor input[value="alpha"]');
  const save = page.locator("#org-grants-save");
  await page.goto(base + "/skills#organization");
  await alpha.check();
  await nav("settings");
  await openSetting(page, "#set-keepalive");
  await page.locator("#set-keepalive").fill("17m");
  await nav("skills");
  await page.locator('.skills-tab[data-tab="organization"]').click();
  assert.equal(await alpha.isChecked(), true, "returning preserves the grants draft");
  const grantsSaved = page.waitForResponse((r) => r.url().endsWith("/api/settings") && r.request().method() === "PUT");
  await save.click();
  const grantResponse = await grantsSaved;
  assert.equal(grantResponse.status(), 200);
  assert.deepEqual(Object.keys(grantResponse.request().postDataJSON()).sort(), ["accessGrants", "connectSlack", "settingsVersion"]);
  assert.deepEqual(getOrgAccessGrants().skills, ["alpha"]);
  // The detail action edits the same organization policy as the bulk editor.
  await page.locator('.skills-tab[data-tab="catalog"]').click();
  await page.locator('tr[data-slug="alpha"]').click();
  await page.locator('[data-action="org-revoke"]').click();
  await page.locator('[data-action="org-grant"]').waitFor();
  assert.deepEqual(getOrgAccessGrants().skills, []);
  await page.locator('[data-action="org-grant"]').click();
  await page.locator('[data-action="org-revoke"]').waitFor();
  assert.deepEqual(getOrgAccessGrants().skills, ["alpha"]);
  await nav("settings");
  await openSetting(page, "#set-keepalive");
  assert.equal(await page.locator("#set-keepalive").inputValue(), "17m");
  const settingsSaved = page.waitForResponse((r) => r.url().endsWith("/api/settings") && r.request().method() === "PUT");
  await page.locator("#save-settings").click();
  const response = await settingsSaved;
  assert.equal(response.status(), 200, "the local grant save advances the Settings draft's version");
  assert.equal(Object.hasOwn(response.request().postDataJSON(), "accessGrants"), false);
  await nav("skills");
  await page.locator('.skills-tab[data-tab="organization"]').click();
  await alpha.uncheck();
  saveSettings({ accessGrants: { skills: ["beta"] } });
  await save.click();
  await page.getByText("Grants changed elsewhere.", { exact: false }).waitFor();
  assert.deepEqual(getOrgAccessGrants().skills, ["beta"]);
  await page.locator("#org-grants-discard").click();
  await page.waitForFunction(() => globalThis.document.querySelector('#org-grants-editor input[value="beta"]')?.checked);
  await page.locator("#org-grant-tier").selectOption("user");
  await page.locator('#users tr[data-id="U_TEST"]').click();
  await page.locator(".ud-grant-tier").selectOption("organization");
  assert.equal(page.url(), base + "/skills#organization");
  await nav("variables");
  const secret = page.locator("#org-secrets-card");
  await secret.locator(".secret-name").fill("EXAMPLE_TOKEN");
  await secret.locator(".secret-value").fill("dummy-variable-fixture-abcd");
  await secret.locator(".secret-save").click();
  await secret.getByText("••••abcd", { exact: true }).waitFor();
  assert.equal(await secret.locator(".secret-value").inputValue(), "");
  await page.reload();
  await secret.getByText("EXAMPLE_TOKEN", { exact: true }).waitFor();
  assert.doesNotMatch(await secret.textContent(), /dummy-variable-fixture/);
  testLicenseEnv({ tier: "free" });
  await page.reload();
  await secret.getByText("Enterprise is required", { exact: false }).waitFor();
  assert.equal(await secret.locator(".secret-save").isDisabled(), true);
  assert.equal(await secret.locator(".secret-remove").isEnabled(), true, "existing variables can be removed after a downgrade");
  assert.deepEqual(errors, []);
});
