// Disposable real API + browser state. Set CG_BROWSER_MODULE to the installed Playwright module.
import test from "node:test";
import assert from "node:assert/strict";
import path from "node:path";
import { fileURLToPath } from "node:url";
import express from "express";
import { ensureTestEnv, testLicenseEnv } from "./helpers.js";
ensureTestEnv();

test("organization instruction licensing preserves values, locks editing and supports explicit clearing", { skip: !process.env.CG_BROWSER_MODULE }, async (t) => {
  const { chromium } = await import(process.env.CG_BROWSER_MODULE);
  const { createAdminRouter } = await import("../src/web/routes/admin.js");
  const settings = await import("../src/config/settings.js");
  settings.saveSettings({ agentsInstructions: "Saved organization rule." });
  testLicenseEnv({ tier: "free" });
  const app = express();
  app.use(express.json());
  app.get("/api/auth/me", (_req, res) => res.json({ authenticated: true, role: "admin" }));
  app.get("/api/skills", (_req, res) => res.json({ skills: [] }));
  app.get("/api/mcp/available", (_req, res) => res.json({ servers: [] }));
  app.get("/api/health", (_req, res) => res.json({ slack: { connected: false, status: "off" }, engines: {} }));
  app.use("/api", createAdminRouter({ slack: { snapshot: () => ({ status: "disconnected", connected: false }) } }));
  const publicDir = fileURLToPath(new URL("../public", import.meta.url));
  app.use(express.static(publicDir, { dotfiles: "allow" }));
  app.get("/settings", (_req, res) => res.sendFile(path.join(publicDir, "index.html"), { dotfiles: "allow" }));
  const server = await new Promise((resolve) => { const s = app.listen(0, "127.0.0.1", () => resolve(s)); });
  t.after(() => new Promise((resolve) => { server.closeAllConnections(); server.close(resolve); }));
  const browser = await chromium.launch({ headless: true, args: ["--no-sandbox"] });
  t.after(() => browser.close());
  const page = await browser.newPage({ viewport: { width: 1366, height: 1000 } });
  page.setDefaultTimeout(10000);
  const errors = [];
  t.after(() => { if (errors.length) console.error(errors); });
  page.on("pageerror", (error) => errors.push(error.message));
  await page.goto(`http://127.0.0.1:${server.address().port}/settings`);
  const field = page.locator("#set-agents-instructions");
  await page.waitForFunction(() => document.querySelector("#set-agents-instructions")?.value === "Saved organization rule.");
  await page.waitForFunction(() => document.querySelector("#set-agents-instructions")?.readOnly === true);
  assert.match(await page.locator("#organization-instructions-entitlement").textContent(), /remain active/);
  await page.locator("#clear-organization-instructions").click();
  assert.equal(await field.inputValue(), "");
  const response = page.waitForResponse(r => r.url().endsWith("/api/settings") && r.request().method() === "PUT");
  await page.locator("#save-settings").click();
  assert.equal((await response).status(), 200);
  assert.equal(settings.getAgentsInstructions(), "");
  testLicenseEnv({ tier: "enterprise" });
  await page.reload();
  await page.waitForFunction(() => document.querySelector("#set-agents-instructions")?.readOnly === false);
  await field.fill("Updated Enterprise policy.");
  const saved = page.waitForResponse(r => r.url().endsWith("/api/settings") && r.request().method() === "PUT");
  await page.locator("#save-settings").click();
  assert.equal((await saved).status(), 200);
  assert.equal(settings.getAgentsInstructions(), "Updated Enterprise policy.");
  assert.deepEqual(errors, []);
});
