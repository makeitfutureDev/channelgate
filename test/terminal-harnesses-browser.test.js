import test from "node:test";
import assert from "node:assert/strict";
import path from "node:path";
import { fileURLToPath } from "node:url";
import express from "express";
import { ensureTestEnv } from "./helpers.js";
ensureTestEnv();

test("optional harness settings expose terminal setup and persist independent activation and defaults", { skip: !process.env.CG_BROWSER_MODULE }, async (t) => {
  const { chromium } = await import(process.env.CG_BROWSER_MODULE);
  const { createAdminRouter } = await import("../src/web/routes/admin.js");
  const { saveSettings, getDefaultModel, getDefaultEffort, isEngineEnabled } = await import("../src/config/settings.js");
  saveSettings({ engine: "claude", engineEnabled: undefined });
  const app = express();
  app.use(express.json());
  app.get("/api/auth/me", (_req, res) => res.json({ bootstrap: false, linkRequired: false, fresh: true, account: { userId: "U_BROWSER_ADMIN" }, passkeys: [] }));
  app.get("/api/skills", (_req, res) => res.json({ skills: [] }));
  app.get("/api/mcp/available", (_req, res) => res.json({ servers: [] }));
  app.get("/api/health", (_req, res) => res.json({ slack: { connected: false, status: "off" }, engines: {} }));
  app.use("/api", createAdminRouter({ slack: { snapshot: () => ({ status: "disconnected", connected: false }) } }));
  const publicDir = fileURLToPath(new URL("../public", import.meta.url));
  app.use(express.static(publicDir, { dotfiles: "allow" }));
  app.get("/settings", (_req, res) => res.sendFile(path.join(publicDir, "index.html"), { dotfiles: "allow" }));
  const server = await new Promise((resolve) => { const s = app.listen(0, "127.0.0.1", () => resolve(s)); });
  t.after(() => new Promise((resolve) => { server.closeAllConnections(); server.close(resolve); }));
  const browser = await chromium.launch({ headless: true, executablePath: process.env.CG_BROWSER_EXECUTABLE || undefined, args: ["--no-sandbox"] });
  t.after(() => browser.close());
  const page = await browser.newPage({ viewport: { width: 1440, height: 1000 } });
  await page.context().grantPermissions(["clipboard-read", "clipboard-write"]);
  page.setDefaultTimeout(10000);
  const errors = [];
  page.on("pageerror", (error) => errors.push(error.message));
  await page.goto(`http://127.0.0.1:${server.address().port}/settings`);
  const cards = page.locator(".terminal-harness-card");
  await cards.first().waitFor();
  assert.equal(await cards.count(), 2);
  const eu = cards.nth(0);
  const bedrock = cards.nth(1);
  assert.match(await eu.locator('[data-role="command"]').textContent(), /CODEX_HOME=.*login --device-auth/);
  assert.match(await bedrock.locator('[data-role="description"]').textContent(), /\/setup-bedrock.*API key.*not supported/);
  for (const card of [eu, bedrock]) {
    const command = await card.locator('[data-role="command"]').textContent();
    await card.locator('[data-role="copy-command"]').click();
    await page.waitForFunction((el) => el.textContent === "Copied", await card.locator('[data-role="copy-state"]').elementHandle());
    assert.equal(await page.evaluate(() => navigator.clipboard.readText()), command, "copies the exact command from its own card");
    assert.equal(await card.locator('[data-role="copy-state"]').textContent(), "Copied");
  }
  // Exercise the HTTP fallback against the browser's real clipboard, then deny both APIs.
  await page.evaluate(() => Object.defineProperty(navigator, "clipboard", { configurable: true, value: undefined }));
  await eu.locator('[data-role="copy-command"]').click();
  await page.waitForFunction((el) => el.textContent === "Copied", await eu.locator('[data-role="copy-state"]').elementHandle());
  assert.equal(await eu.locator('[data-role="copy-state"]').textContent(), "Copied");
  await page.evaluate(() => { delete navigator.clipboard; });
  assert.equal(await page.evaluate(() => navigator.clipboard.readText()), await eu.locator('[data-role="command"]').textContent());
  await page.evaluate(() => {
    Object.defineProperty(navigator, "clipboard", { configurable: true, value: { writeText: () => Promise.reject(new Error("denied")) } });
    globalThis.document.execCommand = () => false;
  });
  await bedrock.locator('[data-role="copy-command"]').click();
  await page.waitForFunction(() => [...globalThis.document.querySelectorAll('[data-role="copy-state"]')].some((el) => el.textContent.startsWith("Could not copy")));
  assert.match(await bedrock.locator('[data-role="copy-state"]').textContent(), /copy it manually/);
  const toggles = page.locator("#engine-enabled-box label");
  const euToggle = toggles.filter({ hasText: "Codex EU" }).locator("input");
  const bedrockToggle = toggles.filter({ hasText: "Claude Bedrock" }).locator("input");
  assert.equal(await euToggle.isChecked(), false);
  assert.equal(await bedrockToggle.isChecked(), false);
  await euToggle.check();
  await bedrockToggle.check();
  await eu.locator('[data-role="default-model"]').selectOption("gpt-6-sol");
  await eu.locator('[data-role="default-effort"]').selectOption("high");
  await bedrock.locator('[data-role="default-model"]').selectOption("sonnet");
  await bedrock.locator('[data-role="default-effort"]').selectOption("medium");
  const response = page.waitForResponse((r) => r.url().endsWith("/api/settings") && r.request().method() === "PUT");
  await page.locator("#save-settings").click();
  assert.equal((await response).status(), 200);
  assert.equal(isEngineEnabled("codex-eu"), true);
  assert.equal(isEngineEnabled("claude-bedrock"), true);
  assert.equal(getDefaultModel("codex-eu"), "gpt-6-sol");
  assert.equal(getDefaultEffort("claude-bedrock"), "medium");
  await page.reload();
  await cards.first().waitFor();
  assert.equal(await euToggle.isChecked(), true);
  assert.equal(await bedrockToggle.isChecked(), true);
  assert.equal(await eu.locator('[data-role="default-model"]').inputValue(), "gpt-6-sol");
  assert.equal(await bedrock.locator('[data-role="default-effort"]').inputValue(), "medium");
  assert.deepEqual(errors, []);
});
