import { openActivityRowActions, selectActivityFilter } from "./activity-browser-controls.js";
import test from "node:test";
import assert from "node:assert/strict";
import express from "express";
import { ensureTestEnv } from "./helpers.js";
ensureTestEnv();
const { setUser, upsertChannelEntry, getChannelEntry, saveChannelMeta } = await import("../src/config/store.js");
const { indexSlackThread, recordSlackThreadParticipation } = await import("../src/gateway/slack-threads.js");
const { createActivityRouter, createActivityGrantUrl, resetActivityStateForTests } = await import("../src/web/activity.js");

test("Activity Hide/Hidden/Show works for participants on desktop and phone, including pinned rows", { skip: !process.env.CG_BROWSER_MODULE, timeout: 40_000 }, async (t) => {
  const owner = "UHIDEOWNER", viewer = "UHIDEVIEWER", channelId = "C_HIDE", threadTs = "100.000001";
  resetActivityStateForTests();
  for (const userId of [owner, viewer]) await setUser(userId, { approved: true });
  await upsertChannelEntry(channelId, { name: "Shared work", type: "channel" });
  const entry = await getChannelEntry(channelId);
  await saveChannelMeta(entry.slug, { access: "approved" });
  const root = { ts: threadTs, user: owner, text: "Shared conversation" };
  indexSlackThread({ channelId, slug: entry.slug, root, agentEngaged: true });
  recordSlackThreadParticipation(channelId, threadTs, viewer, "101.000001");
  const client = { conversations: { replies: async () => ({ messages: [root] }) } };
  const app = express(); let base;
  app.use("/activity", createActivityRouter({ getClient: () => client, getTeamId: () => "THIDE", getBaseUrl: () => base }));
  const server = await new Promise((resolve) => { const s = app.listen(0, "127.0.0.1", () => resolve(s)); });
  base = `http://127.0.0.1:${server.address().port}`;
  t.after(() => new Promise((resolve) => { resetActivityStateForTests(); server.closeAllConnections(); server.close(resolve); }));
  const { chromium } = await import(process.env.CG_BROWSER_MODULE);
  const browser = await chromium.launch({ headless: true, executablePath: process.env.CG_BROWSER_EXECUTABLE });
  t.after(() => browser.close());
  const context = await browser.newContext(), page = await context.newPage();
  page.setDefaultTimeout(5000);
  const errors = []; page.on("pageerror", (error) => errors.push(error.message));
  await page.goto(createActivityGrantUrl({ baseUrl: base, ownerId: viewer, teamId: "THIDE" }));
  const title = page.getByRole("link", { name: root.text, exact: true });
  await title.waitFor();
  assert.equal(await page.getByRole("button", { name: "Mark done: " + root.text, exact: true }).isVisible(), false);
  await page.getByRole("button", { name: "Pin: " + root.text, exact: true }).click();
  await page.locator("#pinned-threads tr").waitFor();
  for (const width of [1440, 390]) {
    await page.setViewportSize({ width, height: 900 });
    await openActivityRowActions(page, root.text);
    await page.getByRole("button", { name: "Hide: " + root.text, exact: true }).click();
    await page.waitForFunction(() => !globalThis.document.querySelector("#pinned-threads tr") && !globalThis.document.querySelector("#threads tr"));
    // Row visibility updates optimistically; the server snapshot supplies the tab counts.
    await page.locator('#filters button[data-filter="active"] span').filter({ hasText: /^0$/ }).waitFor({ state: "attached" });
    await selectActivityFilter(page, "hidden");
    const show = page.getByRole("button", { name: "Show: " + root.text, exact: true });
    await openActivityRowActions(page, root.text);
    await show.waitFor();
    assert.equal(await page.evaluate(() => globalThis.document.documentElement.scrollWidth <= globalThis.innerWidth), true);
    await show.click();
    await page.waitForFunction(() => !globalThis.document.querySelector("#threads tr"));
    await selectActivityFilter(page, "active");
    await title.waitFor();
  }
  await openActivityRowActions(page, root.text);
  await page.getByRole("button", { name: "Hide: " + root.text, exact: true }).click();
  await page.reload();
  await selectActivityFilter(page, "hidden");
  await openActivityRowActions(page, root.text);
  await page.getByRole("button", { name: "Show: " + root.text, exact: true }).waitFor();
  recordSlackThreadParticipation(channelId, threadTs, viewer, (Date.now() / 1000 + 1).toFixed(6));
  await page.waitForFunction(() => !globalThis.document.querySelector("#threads tr"));
  await selectActivityFilter(page, "active");
  await title.waitFor();
  assert.deepEqual(errors, []);
});
