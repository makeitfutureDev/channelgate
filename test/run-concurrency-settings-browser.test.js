// Disposable real API + browser state. Set CG_BROWSER_MODULE to the installed Playwright module.
import test from "node:test";
import assert from "node:assert/strict";
import path from "node:path";
import { fileURLToPath } from "node:url";
import express from "express";
import { ensureTestEnv } from "./helpers.js";
ensureTestEnv();

test("parallel run controls save, reload and explain reservations independently of containers", { skip: !process.env.CG_BROWSER_MODULE }, async (t) => {
  const { chromium } = await import(process.env.CG_BROWSER_MODULE);
  const { createAdminRouter } = await import("../src/web/routes/admin.js");
  const settings = await import("../src/config/settings.js");
  const app = express();
  app.use(express.json());
  // This focused router fixture represents an authenticated admin; real login is tested separately.
  app.get("/api/auth/me", (_req, res) => res.json({ bootstrap: false, linkRequired: false, fresh: true, account: { userId: "U_BROWSER_ADMIN" }, passkeys: [] }));
  app.get("/api/skills", (_req, res) => res.json({ skills: [] }));
  app.get("/api/mcp/available", (_req, res) => res.json({ servers: [] }));
  app.get("/api/health", (_req, res) => res.json({ slack: { connected: false, status: "off" }, engines: {} }));
  app.use("/api", createAdminRouter({ slack: { snapshot: () => ({ status: "disconnected", connected: false }) } }));
  const publicDir = fileURLToPath(new URL("../public", import.meta.url));
  app.use(express.static(publicDir, { dotfiles: "allow" }));
  app.get("/settings", (_req, res) => res.sendFile(path.join(publicDir, "index.html"), { dotfiles: "allow" }));
  const server = await new Promise((resolve) => { const s = app.listen(0, "127.0.0.1", () => resolve(s)); });
  t.after(() => new Promise((resolve) => { server.closeAllConnections(); server.close(resolve); }));
  const browser = await chromium.launch({ headless: true, args: ["--no-sandbox"] });
  t.after(() => browser.close());
  const page = await browser.newPage({ viewport: { width: 1366, height: 1000 } });
  page.setDefaultTimeout(10000);
  const errors = [];
  page.on("pageerror", (error) => errors.push(error.message));
  await page.goto(`http://127.0.0.1:${server.address().port}/settings`);
  const total = page.locator("#set-max-concurrent-runs");
  const reserved = page.locator("#set-reserved-interactive-runs");
  await page.waitForFunction(() => globalThis.document.querySelector("#set-max-concurrent-runs")?.value === "8");
  await total.scrollIntoViewIfNeeded();
  assert.equal(await reserved.inputValue(), "2");
  assert.match(await total.locator("xpath=../..").textContent(), /separate from the running-container limit/);
  await reserved.fill("");
  await page.locator("#save-settings").click();
  await page.waitForFunction(() => globalThis.document.querySelector("#settings-saved")?.textContent.includes("Reserved interactive slots must be a whole number"));
  assert.deepEqual(settings.getRunConcurrency(), { maxConcurrentRuns: 8, reservedInteractiveRuns: 2 });
  await total.fill("32");
  await reserved.fill("0");
  const response = page.waitForResponse((r) => r.url().endsWith("/api/settings") && r.request().method() === "PUT");
  await page.locator("#save-settings").click();
  assert.equal((await response).status(), 200);
  await page.waitForFunction(() => globalThis.document.querySelector("#settings-dirty-msg")?.textContent === "All changes saved");
  assert.deepEqual(settings.getRunConcurrency(), { maxConcurrentRuns: 32, reservedInteractiveRuns: 0 });
  assert.equal(settings.getContainerRuntime().maxRunning, 8);
  await page.reload();
  await page.waitForFunction(() => globalThis.document.querySelector("#set-max-concurrent-runs")?.value === "32");
  assert.equal(await reserved.inputValue(), "0");
  await page.setViewportSize({ width: 390, height: 844 });
  await total.scrollIntoViewIfNeeded();
  assert.equal(await total.isVisible(), true);
  assert.equal(await page.evaluate(() => globalThis.document.documentElement.scrollWidth <= globalThis.innerWidth), true);
  assert.deepEqual(errors, []);
});
